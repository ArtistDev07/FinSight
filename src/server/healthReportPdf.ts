/**
 * Financial Health Snapshot PDF Report Generator (using pdfkit)
 */
import PDFDocument from 'pdfkit';
import type { FinancialHealthDimension } from '../types';

function fmtInrPlain(amt: number): string {
  const safe = Number.isFinite(amt) ? amt : 0;
  return `INR ${safe.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export async function generateHealthReportPdfBuffer(input: {
  userName: string;
  userEmail: string;
  generatedAt: string;
  summary: {
    totalAssets: number;
    totalLiabilities: number;
    estimatedNetWorth: number;
    monthlyIncome: number;
    monthlyExpenses: number;
    monthlySavings: number;
    savingsRate: number;
    emergencyFundCoverageMonths: number;
    compositeIndex: number;
    formulaDisclosure: string;
    missingDataNotes: string[];
    dimensions: FinancialHealthDimension[];
    observations: Array<{ id: string; title: string; calculation: string; severity: string }>;
  };
}): Promise<Buffer> {
  return await new Promise<Buffer>((resolve, reject) => {
    const doc = new PDFDocument({ margin: 45, size: 'A4' });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(20).fillColor('#123D32').text('FinSight Financial Health Report');
    doc.fontSize(9.5).fillColor('#53675E').text(`Prepared for: ${input.userName} (${input.userEmail})`);
    doc.text(`Generated: ${new Date(input.generatedAt).toLocaleString('en-IN')} | Currency: INR`);
    doc.moveDown(0.8);
    doc.moveTo(45, doc.y).lineTo(550, doc.y).strokeColor('#DEE7E0').stroke();
    doc.moveDown(1);

    // Composite score + summary grid
    doc.fontSize(13).fillColor('#172923').text(`Financial Health Index: ${input.summary.compositeIndex} / 100`);
    doc.fontSize(8.5).fillColor('#53675E').text(input.summary.formulaDisclosure);
    doc.moveDown(0.8);

    const rows: Array<[string, string]> = [
      ['Estimated Net Worth', fmtInrPlain(input.summary.estimatedNetWorth)],
      ['Total Tracked Assets', fmtInrPlain(input.summary.totalAssets)],
      ['Total Tracked Liabilities', fmtInrPlain(input.summary.totalLiabilities)],
      ['Recorded Income', fmtInrPlain(input.summary.monthlyIncome)],
      ['Recorded Expenses (excl. transfers/card settlements)', fmtInrPlain(input.summary.monthlyExpenses)],
      ['Net Monthly Surplus & Savings Rate', `${fmtInrPlain(input.summary.monthlySavings)} (${input.summary.savingsRate}%)`],
      ['Emergency Reserve Coverage', `${input.summary.emergencyFundCoverageMonths} months of expenses`],
    ];

    doc.fontSize(9.5);
    for (const [label, val] of rows) {
      const y = doc.y;
      doc.fillColor('#53675E').text(label, 45, y, { width: 320 });
      doc.fillColor('#172923').text(val, 370, y, { width: 180, align: 'right' });
      doc.moveDown(0.35);
    }

    doc.moveDown(0.8);
    doc.fontSize(12).fillColor('#123D32').text('Dimension Breakdown');
    doc.moveDown(0.4);
    for (const dim of input.summary.dimensions) {
      doc.fontSize(10).fillColor('#172923').text(`${dim.label}: ${dim.score}/100 (${dim.status}) · Weight ${Math.round(dim.weight * 100)}%`);
      doc.fontSize(8.5).fillColor('#53675E').text(`Formula: ${dim.formulaSummary} | Evidence: ${dim.evidenceText}`);
      doc.moveDown(0.4);
    }

    if (input.summary.observations.length > 0) {
      doc.moveDown(0.5);
      doc.fontSize(12).fillColor('#123D32').text('Evidence-Based Observations');
      doc.moveDown(0.4);
      for (const obs of input.summary.observations) {
        doc.fontSize(9.5).fillColor('#172923').text(`• ${obs.title}`);
        doc.fontSize(8.5).fillColor('#53675E').text(`  ${obs.calculation}`);
        doc.moveDown(0.3);
      }
    }

    if (input.summary.missingDataNotes.length > 0) {
      doc.moveDown(0.5);
      doc.fontSize(11).fillColor('#C48A32').text('Missing Data / Estimate Notes');
      for (const note of input.summary.missingDataNotes) {
        doc.fontSize(8.5).fillColor('#53675E').text(`- ${note}`);
      }
    }

    doc.moveDown(1.5);
    doc.fontSize(8).fillColor('#819188').text(
      'Educational & personal clarity report generated by FinSight. Calculations use verified user-entered records only. Consult a SEBI-registered advisor or Chartered Accountant for formal advisory or tax filing.',
      { align: 'center' }
    );

    doc.end();
  });
}
